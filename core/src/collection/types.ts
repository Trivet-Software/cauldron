// Collection repository types (01.7-walking-skeleton task 5.2, design.md, "Collection
// repository"). Node-only, like the rest of `@cauldron/core/collection`.
import { type RequestActor, type UserActor } from '../db'
import { type CompileState } from '../compile'
import { type GoalFile } from '../goals'

export type CaptureClient = 'web' | 'mcp'
export type CaptureKind = 'text' | 'photo'

export interface GoalRecord {
  id: string
  slug: string
  name: string
  description: string | null
  icon: string | null
  accentColor: string | null
  /** The goal's latest version number, the one `spec` belongs to. */
  version: number
  spec: GoalFile
}

export interface CaptureMetadata {
  /** What the list shows while the capture is pending or failed (`captureLabel`). */
  label: string
  filename?: string
  contentType: string
  bytes: number
}

export interface NewCapture {
  /** Generated by the API before the upload, so the storage path can contain it. */
  sourceId: string
  goalId: string
  kind: CaptureKind
  client: CaptureClient
  storagePath: string
  metadata: CaptureMetadata
}

export interface SourceStatus {
  id: string
  /** Goal slug. */
  goal: string
  kind: CaptureKind
  client: CaptureClient | 'api'
  capturedAt: string
  state: CompileState
  failureReason: string | null
  itemId: string | null
}

/** One row per source, newest capture first. */
export interface ItemEntry {
  /** The item's ID; null until the capture has compiled. */
  id: string | null
  sourceId: string
  /** The item title, or the capture label while pending or failed. */
  title: string
  state: CompileState
  failureReason: string | null
  /** ISO 8601. */
  capturedAt: string
}

export interface ItemRecord {
  id: string
  sourceId: string
  goalSlug: string
  goalVersion: number
  title: string
  data: Record<string, unknown>
  /** The storage path held by the goal's image field, for signing; null when there is none. */
  imagePath: string | null
  capturedAt: string
}

export interface ListItemsQuery {
  goalSlug: string
  q?: string
  limit: number
}

/** What the API depends on (as `deps.collection`), so route tests can inject a fake. */
export interface CollectionStore {
  listGoals(actor: RequestActor): Promise<GoalRecord[]>
  getGoal(actor: RequestActor, slug: string): Promise<GoalRecord | null>
  createCapture(
    actor: UserActor,
    input: NewCapture,
  ): Promise<{ sourceId: string; state: CompileState }>
  getSource(actor: UserActor, sourceId: string): Promise<SourceStatus | null>
  listItems(actor: UserActor, query: ListItemsQuery): Promise<ItemEntry[]>
  getItem(actor: UserActor, itemId: string): Promise<ItemRecord | null>
}

/** What the compile handler needs, loaded inside the job user's scope. */
export interface CompileInput {
  sourceId: string
  kind: CaptureKind
  /** The raw source's storage path; null if the source row has none. */
  storagePath: string | null
  metadata: CaptureMetadata
  goal: {
    id: string
    slug: string
    /** The latest version at compile time; saved on the item as `goal_version`. */
    version: number
    spec: GoalFile
  }
}

export interface NewItem {
  sourceId: string
  goalId: string
  goalVersion: number
  /** The validated item's title-field value. Stored as `title` and as `search_text`. */
  title: string
  data: Record<string, unknown>
  /** For example `{ mode: 'mapper', sourceKind: 'text' }`. */
  provenance: Record<string, unknown>
}

export interface NewUsage {
  sourceId: string
  /** The running job's ID; omit to leave `job_id` null. */
  jobId?: string
  provider: string
  model: string
  inputTokens: number
  outputTokens: number
  costUsd: number
}
